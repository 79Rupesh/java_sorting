public class Unary_Operators {
    public static void main(String args[]) {
        int a = 10;
        int b = 10;
        int c = 10;
        int d = 10;
        int e = 10;
        int f = 10;

        System.out.println("Unary Operators = " + (a));
        System.out.println("Unary Operators = " + (b++));
        System.out.println("Unary Operators = " + (+c));
        System.out.println("Unary Operators = " + (++d));
        System.out.println("Unary Operators = " + (-e));
        System.out.println("Unary Operators = " + (--f));
    }
}
